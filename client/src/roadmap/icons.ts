// Ícones e avatares em pixel art da página de roadmap. Mesmo espírito do escritório: cada "#"
// é um pixel pintado com currentColor; avatares usam uma paleta pequena por personagem.
import type { AvatarId, Provider } from './data';

function pixelPaths(rows: readonly string[], palette: Readonly<Record<string, string>>): string {
  let out = '';
  for (const [ch, color] of Object.entries(palette)) {
    let d = '';
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== ch) {
          x += 1;
          continue;
        }
        let run = 1;
        while (row[x + run] === ch) run += 1;
        d += `M${x} ${y}h${run}v1h-${run}z`;
        x += run;
      }
    });
    if (d) out += `<path fill="${color}" d="${d}"/>`;
  }
  return out;
}

function pixelSvg(rows: readonly string[], palette: Readonly<Record<string, string>>, cls: string, scale = 2): string {
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  return `<svg class="${cls}" width="${w * scale}" height="${h * scale}" viewBox="0 0 ${w} ${h}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${pixelPaths(rows, palette)}</svg>`;
}

function icon(rows: readonly string[]): string {
  return pixelSvg(rows, { '#': 'currentColor' }, 'rp-px-icon');
}

